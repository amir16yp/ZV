    private string Generate(string source)
    {
        var lexer = new ZV.Compiler.Lexer.Lexer(source);
        var tokens = lexer.ScanTokens();
        var parser = new ZV.Compiler.Parser.Parser(tokens);
        var statements = parser.Parse();
        if (parser.HadError)
        {
            throw new System.Exception("Parse error(s): " + string.Join("; ", parser.Errors.ConvertAll(e => e.Message)));
        }
        using var generator = new LlvmGenerator("test_module");
        generator.Generate(statements);
        return generator.EmitToString();
    }

    // Like Generate(), but also runs LLVM's module verifier. EmitToString() alone won't
    // catch bugs like a type created in the wrong LLVMContextRef (e.g. the INT16/INT128
    // context-mismatch bug below) - the textual IR still prints "fine", but LLVM's verifier
    // (and, further down the pipeline, clang) rejects it.
    private void GenerateAndVerify(string source)
    {
        var lexer = new ZV.Compiler.Lexer.Lexer(source);
        var tokens = lexer.ScanTokens();
        var parser = new ZV.Compiler.Parser.Parser(tokens);
        var statements = parser.Parse();
        if (parser.HadError)
        {
            throw new System.Exception("Parse error(s): " + string.Join("; ", parser.Errors.ConvertAll(e => e.Message)));
        }
        using var generator = new LlvmGenerator("test_module");
        generator.Generate(statements);
        Assert.True(generator.TryVerify(out var message), $"Module failed LLVM verification: {message}");
    }

    // Compiles the generated IR with clang and runs the resulting executable. Returns
    // the captured stdout, or null if clang is unavailable so the caller can skip.
    private static string? CompileAndRunIr(string ir)
    {
        var tempDir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
        Directory.CreateDirectory(tempDir);
        try
        {
            var llPath = Path.Combine(tempDir, "test.ll");
            var exePath = RuntimeInformation.IsOSPlatform(OSPlatform.Windows)
                ? Path.Combine(tempDir, "test.exe")
                : Path.Combine(tempDir, "test");
            // Test IR only defines @test(); add a main entry point so clang can build
            // a runnable executable.
            ir += @"
define i32 @main(i32 %0, ptr %1) {
entry:
  call void @test()
  ret i32 0
}
";
            File.WriteAllText(llPath, ir);

            try
            {
                Program.CompileWithClang(llPath, exePath, Enumerable.Empty<string>());
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Skipping runtime test: clang compilation failed: {ex.Message}");
                return null;
            }

            if (!File.Exists(exePath))
            {
                Console.WriteLine("Skipping runtime test: clang did not produce an executable.");
                return null;
            }

            var psi = new ProcessStartInfo
            {
                FileName = exePath,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
            };
            using var process = Process.Start(psi)!;
            process.WaitForExit(30000);
            if (process.ExitCode != 0)
            {
                throw new Exception($"Runtime test executable exited with {process.ExitCode}: {process.StandardError.ReadToEnd()}");
            }
            return process.StandardOutput.ReadToEnd();
        }
        finally
        {
            try { Directory.Delete(tempDir, recursive: true); } catch { }
        }
    }

    // Counts `call void @free` only in user-defined functions, ignoring destructor
    // functions generated by the cleanup stack.
    private static int CountFreeCallsInUserCode(string ir)
    {
        int dtorIndex = ir.IndexOf("define internal void @_zv_dtor_");
        string userIr = dtorIndex >= 0 ? ir.Substring(0, dtorIndex) : ir;
        return userIr.Split("call void @free").Length - 1;
    }

    // Counts cleanup records pushed for owning variables in user-defined functions,
    // ignoring destructor function definitions.
    private static int CountCleanupRecordsPushed(string ir)
    {
        int dtorIndex = ir.IndexOf("define internal void @_zv_dtor_");
        string userIr = dtorIndex >= 0 ? ir.Substring(0, dtorIndex) : ir;
        return System.Text.RegularExpressions.Regex.Matches(userIr, "store ptr @_zv_dtor_[^,]+").Count;
    }


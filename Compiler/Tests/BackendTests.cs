    [Fact]
    public void TestCleanupStackGlobalsAreNotThreadLocalFreestanding()
    {
        // Freestanding targets have no OS TLS runtime, so the cleanup stack falls back to
        // ordinary globals like the exception state.
        string source = @"
VOID test() {
    INT32[] a = INT32[10];
}";
        var lexer = new ZV.Compiler.Lexer.Lexer(source);
        var tokens = lexer.ScanTokens();
        var parser = new ZV.Compiler.Parser.Parser(tokens);
        var statements = parser.Parse();
        using var generator = new LlvmGenerator("test_module") { IsFreestandingTarget = true };
        generator.Generate(statements);
        string ir = generator.EmitToString();
        Assert.Contains("@__zv_cleanup_head = internal global ptr null", ir);
        Assert.Contains("@__zv_cleanup_used = internal global i32 0", ir);
        Assert.Contains("@__zv_cleanup_free = internal global ptr null", ir);
        Assert.DoesNotContain("thread_local", ir);
        Assert.True(generator.TryVerify(out var message), $"Module failed LLVM verification: {message}");
    }


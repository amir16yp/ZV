            Assert.Contains("define i32 @test", ir);
            Assert.Contains("call i32 @add(i32 1, i32 2)", ir);
        }
        finally
        {
            if (File.Exists(headerPath)) File.Delete(headerPath);
            if (File.Exists(sourcePath)) File.Delete(sourcePath);
        }
    }

